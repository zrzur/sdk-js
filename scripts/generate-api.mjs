#!/usr/bin/env node
// Generate the API layer from the server's OpenAPI document.
//
//   node scripts/generate-api.mjs            write src/api/*.ts from api/openapi.json
//   node scripts/generate-api.mjs --check    fail when src/api/ is out of date or a route is missing
//   node scripts/generate-api.mjs --fetch http://127.0.0.1:14702
//                                            refresh api/openapi.json from a running server first
//   node scripts/generate-api.mjs --check --against https://api.example
//                                            also fail when that server has a route the table lacks
//
// Output (never edit by hand):
//   src/api/schema.ts  every schema and operation (openapi-typescript)
//   src/api/types.ts   one named type per schema (`User`, `Message`, …)
//   src/api/routes.ts  the route table: method, path template, parameters, response
//   src/api/params.ts  path shapes and query parameter names used at run time

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SPEC = join(root, "api/openapi.json");
const OUT = join(root, "src/api");
const HEADER = "// Generated by scripts/generate-api.mjs from api/openapi.json. Do not edit.\n";
const METHODS = ["get", "put", "post", "delete", "patch"];

const args = process.argv.slice(2);
const check = args.includes("--check");
const fetchFrom = args.includes("--fetch") ? args[args.indexOf("--fetch") + 1] : undefined;
const against = args.includes("--against") ? args[args.indexOf("--against") + 1] : undefined;

async function serverSpec(base) {
  const response = await fetch(base.replace(/\/$/, "") + "/openapi.json");
  if (!response.ok) throw new Error(`GET ${base}/openapi.json: ${response.status}`);
  return response.json();
}

if (fetchFrom) {
  writeFileSync(SPEC, JSON.stringify(await serverSpec(fetchFrom), null, 2) + "\n");
}

const spec = JSON.parse(readFileSync(SPEC, "utf8"));

/** Every operation in the document: [method, path, operation] */
const operations = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    if (item[method]) operations.push([method, path, item[method]]);
  }
}

const missingIds = operations.filter(([, , op]) => !op.operationId);
if (missingIds.length) {
  fail(missingIds.map(([m, p]) => `${m.toUpperCase()} ${p} has no operationId`));
}

// the server reuses some ids (e.g. two `review_queue`); keep the first, name the others by route
const seen = new Set();
for (const [method, path, op] of operations) {
  if (seen.has(op.operationId)) {
    const unique = `${method}${path.replace(/[^A-Za-z0-9]+/g, "_")}`.replace(/_$/, "");
    console.warn(`warning: duplicate operationId ${op.operationId} at ${method.toUpperCase()} ${path} (using ${unique})`);
    op.operationId = unique;
  }
  seen.add(op.operationId);
}

/* schema.ts ---------------------------------------------------------------- */

const schema =
  HEADER +
  astToString(await openapiTS(spec, {
    alphabetize: false,
    exportType: true,
    // a field with a default may be left out of a request
    defaultNonNullable: false,
  }));

/* types.ts ----------------------------------------------------------------- */

const schemaNames = Object.keys(spec.components?.schemas ?? {});
const types =
  HEADER +
  `import type { components } from "./schema.js";\n\n` +
  schemaNames
    .filter((name) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(name))
    .map((name) => `export type ${name} = components["schemas"]["${name}"];`)
    .join("\n") +
  "\n";

/* routes.ts ---------------------------------------------------------------- */

const template = (path) => path.replace(/\{[^}]+\}/g, "${string}");
const parts = (path) => path.split("/").length - 1;

function jsonOf(content) {
  return content?.["application/json"] ? true : false;
}

function routeLine([method, path, op]) {
  const ref = `operations["${op.operationId}"]`;
  const query = (op.parameters ?? []).some((p) => p.in === "query");
  const body = jsonOf(op.requestBody?.content);

  const params = [
    body ? `NonNullable<${ref}["requestBody"]>["content"]["application/json"]` : null,
    query ? `NonNullable<${ref}["parameters"]["query"]>` : null,
  ].filter(Boolean);

  const success = Object.keys(op.responses ?? {}).find((status) => /^2\d\d$/.test(status));
  const response =
    success && jsonOf(op.responses[success].content)
      ? `${ref}["responses"][${success}]["content"]["application/json"]`
      : "undefined";

  const optional = body && !op.requestBody.required && !query;
  return (
    `  | { method: "${method}"; path: \`${template(path)}\`; template: "${path}"; parts: ${parts(path)}; ` +
    `params: ${params.length ? params.map((p) => `(${p})`).join(" & ") + (optional ? " | undefined" : "") : "undefined"}; response: ${response} }`
  );
}

const routes =
  HEADER +
  `import type { operations } from "./schema.js";\n\n` +
  `/** Every route of the API: what to send and what comes back */\n` +
  `export type APIRoutes =\n` +
  operations.map(routeLine).join("\n") +
  ";\n";

/* params.ts ---------------------------------------------------------------- */

const shapes = {};
const queryParams = {};
for (const [method, path, op] of operations) {
  const segments = path.split("/").slice(1);
  const list = (shapes[segments.length] ??= []);
  const shape = segments.map((s) => (s.startsWith("{") ? [s] : s));
  if (!list.some((entry) => JSON.stringify(entry) === JSON.stringify(shape))) list.push(shape);

  const names = (op.parameters ?? []).filter((p) => p.in === "query").map((p) => p.name);
  if (names.length) (queryParams[path] ??= {})[method] = names;
}

// literal segments win over parameters when both match ("/users/@me" before "/users/{target}")
for (const list of Object.values(shapes)) {
  list.sort((a, b) => a.filter(Array.isArray).length - b.filter(Array.isArray).length);
}

const params =
  HEADER +
  `/** Path shapes by segment count; \`["{x}"]\` is a parameter */\n` +
  `export const pathResolve: Record<string, (string | [string])[][]> = ${JSON.stringify(shapes)};\n\n` +
  `/** Query parameter names by path template and method */\n` +
  `export const queryParams: Record<string, Partial<Record<string, string[]>>> = ${JSON.stringify(queryParams)};\n\n` +
  `/** Every route as "METHOD /template" (checked against the document in CI) */\n` +
  `export const routeList: readonly string[] = ${JSON.stringify(
    operations.map(([m, p]) => `${m.toUpperCase()} ${p}`),
  )};\n`;

/* write or check ----------------------------------------------------------- */

const errorCodes = readFileSync(join(root, "api/error-codes.txt"), "utf8")
  .split(/\r?\n/)
  .filter((line) => line && !line.startsWith("#"));
const errorCodesFile = `// Generated by scripts/generate-api.mjs from api/error-codes.txt. Do not edit.

/** Every value of \`type\` in an API error; never renamed or removed */
export const ERROR_CODES = ${JSON.stringify(errorCodes)} as const;

export type ErrorCode = (typeof ERROR_CODES)[number];
`;

const files = {
  "schema.ts": schema,
  "types.ts": types,
  "routes.ts": routes,
  "params.ts": params,
  "error-codes.ts": errorCodesFile,
};

if (check) {
  const problems = [];
  for (const [name, content] of Object.entries(files)) {
    let current = "";
    try {
      current = readFileSync(join(OUT, name), "utf8");
    } catch {
      // missing file
    }
    if (current.replace(/\r\n/g, "\n") !== content) {
      problems.push(`src/api/${name} is out of date: run pnpm api:generate`);
    }
  }

  // every operation of the document must be in the committed route table
  const table = readFileSync(join(OUT, "routes.ts"), "utf8");
  for (const [method, path] of operations) {
    if (!table.includes(`method: "${method}"; path: \`${template(path)}\`; template: "${path}";`)) {
      problems.push(`missing route: ${method.toUpperCase()} ${path}`);
    }
  }

  // and every operation of a running server (e.g. staging), when given
  if (against) {
    const live = await serverSpec(against);
    for (const [path, item] of Object.entries(live.paths)) {
      for (const method of METHODS) {
        if (item[method] && !table.includes(`method: "${method}"; path: \`${template(path)}\`; template: "${path}";`)) {
          problems.push(`missing route on ${against}: ${method.toUpperCase()} ${path} (run pnpm api:fetch)`);
        }
      }
    }
  }

  if (problems.length) fail(problems);
  console.log(`API layer is up to date (${operations.length} routes, ${schemaNames.length} types).`);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [name, content] of Object.entries(files)) writeFileSync(join(OUT, name), content);
  console.log(`Wrote src/api/ (${operations.length} routes, ${schemaNames.length} types).`);
}

function fail(lines) {
  for (const line of lines) console.error(line);
  process.exit(1);
}
